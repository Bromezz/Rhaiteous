//payloadSchema inlines $ref into envelope
nodeTest.test("flow payloadSchema inlines $ref into envelope", function testPayloadSchema() {

  //variables
  let tmpDir = ""; //temp
  let promptsDir = ""; //prompts
  let schemasDir = ""; //schemas
  let result = null; //compile

  tmpDir = nodeFs.mkdtempSync(nodePath.join(nodeOs.tmpdir(), "wfpay-"));
  promptsDir = nodePath.join(tmpDir, "prompts");
  schemasDir = nodePath.join(tmpDir, "schemas");
  nodeFs.mkdirSync(promptsDir, { recursive: true });
  nodeFs.mkdirSync(schemasDir, { recursive: true });
  nodeFs.writeFileSync(nodePath.join(promptsDir, "a.md"), "A\n", "utf8");
  nodeFs.writeFileSync(
    nodePath.join(schemasDir, "part.schema.json"),
    JSON.stringify({ type: "object", properties: { z: { type: "number" } } }),
    "utf8"
  );
  nodeFs.writeFileSync(
    nodePath.join(schemasDir, "payload.schema.json"),
    JSON.stringify({
      type: "object",
      properties: {
        nested: { $ref: "part.schema.json" },
      },
    }),
    "utf8"
  );

  try {

    result = compileMod.compileWorkflow(
      {
        name: "pay-demo", //name
        description: "payload inline", //desc
        payloadSchema: "payload.schema.json", //payload
        stations: [{ name: "A", prompt: ["a.md"] }],
      },
      { base: tmpDir }
    );

    //inlined nested property from $ref target (Rhai map key may be bare)
    nodeAssert.match(result.rhai, /\bz\b/);
    nodeAssert.match(result.rhai, /"type": "number"|type: "number"/);
    nodeAssert.match(result.rhai, /make_flow_schema/);

  } finally {

    nodeFs.rmSync(tmpDir, { recursive: true, force: true });

  //end try
  }

//end testPayloadSchema
});

