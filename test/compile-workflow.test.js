//compileWorkflowFile writes output
nodeTest.test("compileWorkflowFile writes output", function testCompileFile() {

  //variables
  let outDir = ""; //temp out
  let outPath = ""; //file
  let result = null; //compile
  let text = ""; //written
  let mdBesideJson = ""; //workflow.md next to authoring JSON
  let mdText = ""; //guide body
  let packDir = ""; //pack-style out dir
  let packRhai = ""; //workflow.rhai
  let packMd = ""; //workflow.md beside IR

  outDir = nodeFs.mkdtempSync(nodePath.join(nodeOs.tmpdir(), "wfout-"));
  outPath = nodePath.join(outDir, "example-office-shopping.rhai");
  mdBesideJson = nodePath.join(shoppingPack, "workflow.md");

  try {

    result = compileMod.compileWorkflowFile(shoppingPath, {
      base: shoppingPack, //base
      outPath: outPath, //out
    });

    nodeAssert.equal(result.written, true);
    text = nodeFs.readFileSync(outPath, "utf8");
    nodeAssert.match(text, /fn Intake\(/);
    nodeAssert.match(text, /===== \[intake\.md\] =====/);

    //same cycle: workflow.md beside authoring JSON (always that name)
    nodeAssert.ok(nodeFs.existsSync(mdBesideJson));
    mdText = nodeFs.readFileSync(mdBesideJson, "utf8");
    nodeAssert.match(mdText, /BUILD ARTIFACT/);
    nodeAssert.match(mdText, /# example-office-shopping/);
    nodeAssert.ok(
      result.workflowMdPaths.some(function has(p) {

        //normalized match
        return nodePath.resolve(p) === nodePath.resolve(mdBesideJson);

      //end some
      })
    );

    //pack-style: -o …/workflow.rhai also writes workflow.md beside IR
    packDir = nodePath.join(outDir, "pack");
    packRhai = nodePath.join(packDir, "workflow.rhai");
    packMd = nodePath.join(packDir, "workflow.md");
    result = compileMod.compileWorkflowFile(shoppingPath, {
      base: shoppingPack,
      outPath: packRhai,
    });
    nodeAssert.ok(nodeFs.existsSync(packRhai));
    nodeAssert.ok(nodeFs.existsSync(packMd));
    nodeAssert.match(
      nodeFs.readFileSync(packMd, "utf8"),
      /\/workflow example-office-shopping/
    );

  } finally {

    nodeFs.rmSync(outDir, { recursive: true, force: true });

  //end try
  }

//end testCompileFile
});

