//minimal stations array → phases + fns + next driver
nodeTest.test("compiles stations array to flow IR", function testFlowStations() {

  //variables
  let tmpDir = ""; //temp asset base
  let promptsDir = ""; //prompts dir
  let schemasDir = ""; //schemas dir
  let workflow = null; //flow doc
  let result = null; //compile result

  //temp base with two prompt files + one schema
  tmpDir = nodeFs.mkdtempSync(nodePath.join(nodeOs.tmpdir(), "wfflow-"));
  promptsDir = nodePath.join(tmpDir, "prompts");
  schemasDir = nodePath.join(tmpDir, "schemas");
  nodeFs.mkdirSync(promptsDir, { recursive: true });
  nodeFs.mkdirSync(schemasDir, { recursive: true });
  nodeFs.writeFileSync(
    nodePath.join(promptsDir, "a.md"),
    "Station A body\n",
    "utf8"
  );
  nodeFs.writeFileSync(
    nodePath.join(promptsDir, "b.md"),
    "Station B body\n",
    "utf8"
  );
  nodeFs.writeFileSync(
    nodePath.join(schemasDir, "widget.schema.json"),
    JSON.stringify({ type: "object", properties: { x: { type: "string" } } }),
    "utf8"
  );

  try {

    //two stations
    workflow = {
      name: "flow-demo", //name
      description: "minimal flow", //desc
      schemas: {
        widget: "widget.schema.json", //guidance
      },
      stations: [
        {
          name: "Alpha", //station
          prompt: ["a.md"], //path
          schemas: ["widget"], //guidance
        },
        {
          name: "Beta", //station
          prompt: ["b.md"], //path
          uiDescription: "second phase", //detail
        },
      ],
    };

    //compile
    result = compileMod.compileWorkflow(workflow, {
      base: tmpDir, //base
    });

    //flow IR markers
    nodeAssert.equal(result.scriptType, "flow");
    nodeAssert.match(result.rhai, /fn Alpha\(/);
    nodeAssert.match(result.rhai, /fn Beta\(/);
    nodeAssert.match(result.rhai, /===== \[a\.md\] =====/);
    nodeAssert.match(result.rhai, /===== \[b\.md\] =====/);
    nodeAssert.match(result.rhai, /title: "Alpha"/);
    nodeAssert.match(result.rhai, /title: "Beta"/);
    nodeAssert.match(result.rhai, /detail: "second phase"/);
    nodeAssert.match(result.rhai, /while flow\.next != \(\)/);

  } finally {

    //cleanup
    nodeFs.rmSync(tmpDir, { recursive: true, force: true });

  //end try
  }

//end testFlowStations
});

